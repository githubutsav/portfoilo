/**
 * ⚡ Helper to resolve string path or StaticImageData to a full StaticImageData with blurDataURL
 */
export function getStaticAsset(src: string | StaticImageData | undefined): string | StaticImageData | undefined {
  if (!src) return undefined
  if (typeof src !== 'string') return src
  return IMAGE_ASSET_MAP[src] || src
}
